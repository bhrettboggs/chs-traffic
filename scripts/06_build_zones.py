"""Build LODES zones, connectors and internal commute flows.

    python scripts/06_build_zones.py

Reads data/raw/lodes/*.csv.gz (see data/raw/README.md) and the graph from
scripts/02_build_graph.py; writes three small CSVs to data/reference/:
zones_lodes.csv, zone_connectors.csv, internal_od.csv. Rerun after refetching
OSM (connector node ids change) or changing the zone settings in config.
"""

import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from chstraffic import config, lodes  # noqa: E402

HEADER = ("# Generated by scripts/06_build_zones.py from Census LEHD LODES 8.5 ({year}, JT00/S000),\n"
          "# https://lehd.ces.census.gov/data/lodes/LODES8/sc/ . Do not edit by hand.\n")


def main() -> None:
    D = pickle.loads((ROOT / "data" / "processed" / "chs_digraph.gpickle").read_bytes())
    zones, con, internal, rep = lodes.build(D, ROOT / "data" / "raw" / "lodes")
    ref = ROOT / "data" / "reference"
    for name, df in (("zones_lodes.csv", zones.round({"lat": 6, "lon": 6})),
                     ("zone_connectors.csv", con), ("internal_od.csv", internal)):
        with open(ref / name, "w", newline="") as f:
            f.write(HEADER.format(year=config.LODES_YEAR))
            df.to_csv(f, index=False)
    for k, v in rep.items():
        print(f"{k:>26}: {v}")
    top = zones.assign(activity=zones.jobs + zones.workers).nlargest(8, "activity")
    print("\nlargest zones:\n", top[["zone", "lat", "lon", "jobs", "workers", "n_blocks"]].to_string(index=False))


if __name__ == "__main__":
    main()
