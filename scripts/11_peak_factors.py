"""Peak-hour factors K and directional split per gateway, from SCDOT continuous-count stations.

    python scripts/11_peak_factors.py

Reads data/raw/scdot_ccs_hourly_2025.csv and data/reference/ccs_stations.csv, writes
data/reference/peak_factors.csv (read by demand.py and calibrate.py when
config.PEAK_FACTOR_SOURCE = "ccs") and prints each station's weekday hourly profile.
"""

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from chstraffic import config, peaks  # noqa: E402


def main() -> None:
    ref = ROOT / "data" / "reference"
    zones = pd.read_csv(ref / "zones.csv", comment="#")
    gateways = list(zones.zone_id[zones.kind == "gateway_in"])
    hourly = ROOT / "data" / "raw" / "scdot_ccs_hourly_2025.csv"
    stations = pd.read_csv(ref / "ccs_stations.csv", comment="#", dtype={"station": str})
    g = peaks.group_hourly(peaks.load_hourly(hourly), stations)
    prof = g.groupby(["group", "hour"]).agg(all=("all", "median"), inbound=("inbound", "median")).reset_index()
    prof["in_share"] = (prof.inbound / prof["all"]).round(2)
    pd.set_option("display.width", 200)
    print("Median Tue-Thu volume by hour (both directions) and inbound share, 6-19 h:")
    print(prof[(prof.hour >= 6) & (prof.hour <= 19)].pivot(index="hour", columns="group", values=["all", "in_share"]).to_string())
    print("valid days per group:", g.groupby("group").date.nunique().to_dict())
    out = peaks.factors(hourly, ref / "ccs_stations.csv", gateways)
    header = ("# Peak-hour factor K (peak-hour volume / AADT, both directions) and inbound split per gateway and peak.\n"
              "# GENERATED by scripts/11_peak_factors.py from data/raw/scdot_ccs_hourly_2025.csv; do not edit by hand.\n"
              "# _interior = factor applied to the interior count stations (calibration). p10/p90 = spread across days.\n")
    (ref / "peak_factors.csv").write_text(header + out.to_csv(index=False))
    print(out.drop(columns="source").to_string(index=False))


if __name__ == "__main__":
    main()
